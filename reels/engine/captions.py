"""Build captions.js from story.json caption chunks + the voiceover timing file.
Usage: python3 captions.py <story.json> <vo_timing.json> <out captions.js>
story.json "captions": one list of HTML chunks per VO line; chunk time is proportional to its text length."""
import json, re, sys

story, timing_path, out = sys.argv[1:4]
cfg, timing = json.load(open(story)), json.load(open(timing_path))
end_cap = cfg.get('duration', 60) - 0.4
rows = []
for (st, dur, _), chunks in zip(timing, cfg['captions']):
    lens = [len(re.sub('<[^>]+>', '', c)) for c in chunks]
    t = st
    for i, (c, n) in enumerate(zip(chunks, lens)):
        e = t + dur * n / sum(lens)
        rows.append([round(t, 2), round(min(e + 0.35, end_cap) if i == len(chunks) - 1 else e, 2), c])
        t = e
open(out, 'w').write('// generated by engine/captions.py\nconst CAPTIONS = ' + json.dumps(rows, ensure_ascii=False, indent=0) + ';\n')
print(len(rows), 'captions')
