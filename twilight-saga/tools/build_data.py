#!/usr/bin/env python3
"""Bundle assets/timing.json + assets/plates.json into assets/data.js (loadable from file:// too)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t = json.load(open(f"{ROOT}/assets/timing.json")); m = json.load(open(f"{ROOT}/assets/plates.json"))
open(f"{ROOT}/assets/data.js", "w").write("/* generated by tools/build_data.py: narration timing + plate layout */\n"
                                           f"window.TIMING = {json.dumps(t)};\nwindow.PLATES = {json.dumps(m)};\n")
print("assets/data.js written")
